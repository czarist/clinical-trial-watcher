<?php

declare(strict_types=1);

namespace App\Services\Digests;

/**
 * Accepts the model's JSON only when every summary is tied to a requested change and stays
 * within factual registry language. Anything else is rejected, and the affected changes use
 * the factual summary instead.
 */
final readonly class SummaryValidator
{
    /**
     * Wording that would turn registry facts into advice, an eligibility decision or a claim
     * about efficacy. Matched case-insensitively at the start of a word ("cure" matches
     * "cured" but not "secure").
     */
    private const array FORBIDDEN = [
        // English
        'recommend', 'you should', 'eligib', 'efficac', 'effective', 'proven', 'cure', 'safe and',
        'consult your', 'talk to your doctor', 'enroll now', 'sign up',
        // Brazilian Portuguese
        'recomend', 'você deve', 'elegív', 'elegibilidade', 'eficác', 'eficaz', 'comprovad', 'cura',
        'consulte seu', 'inscreva-se',
    ];

    public function __construct(private int $maxSummaryChars) {}

    /**
     * @param  array<int, string>  $nctIdsByChange  requested change id => the study's NCT number
     * @return array<int, string> accepted summaries keyed by change id
     */
    public function accepted(string $content, array $nctIdsByChange): array
    {
        try {
            $data = json_decode($content, true, 8, JSON_THROW_ON_ERROR);
        } catch (\JsonException) {
            return [];
        }

        if (! is_array($data) || ! isset($data['summaries']) || ! is_array($data['summaries'])) {
            return [];
        }

        $accepted = [];

        foreach ($data['summaries'] as $item) {
            if (! is_array($item) || ! is_int($item['change_id'] ?? null) || ! is_string($item['summary'] ?? null)) {
                continue;
            }

            $changeId = $item['change_id'];
            $summary = trim($item['summary']);

            if (! isset($nctIdsByChange[$changeId]) || isset($accepted[$changeId])) {
                continue;
            }

            if ($this->isAcceptable($summary, $nctIdsByChange[$changeId])) {
                $accepted[$changeId] = $summary;
            }
        }

        return $accepted;
    }

    public function isAcceptable(string $summary, string $nctId): bool
    {
        if ($summary === '' || mb_strlen($summary) > $this->maxSummaryChars) {
            return false;
        }

        // Links are generated by the application, never by the model.
        if (preg_match('~https?://|www\.|\]\(~i', $summary) === 1) {
            return false;
        }

        // Only the study's own NCT number may appear.
        preg_match_all('/NCT\d{8}/i', $summary, $mentioned);

        foreach ($mentioned[0] as $id) {
            if (strtoupper($id) !== $nctId) {
                return false;
            }
        }

        foreach (self::FORBIDDEN as $term) {
            if (preg_match('/(?<![\p{L}\p{N}])'.preg_quote($term, '/').'/iu', $summary) === 1) {
                return false;
            }
        }

        return true;
    }
}
